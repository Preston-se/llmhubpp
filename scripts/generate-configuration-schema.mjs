import ts from 'typescript';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
const config=ts.readConfigFile('tsconfig.json',ts.sys.readFile);
const parsed=ts.parseJsonConfigFileContent(config.config,ts.sys,'.');
const program=ts.createProgram(parsed.fileNames,parsed.options),checker=program.getTypeChecker();
function schema(type,depth=0){
  if(depth>10)return {type:'unknown'};
  if(type.isUnion()){
    const parts=type.types.filter(t=>!(t.flags & ts.TypeFlags.Undefined));
    if(parts.every(t=>t.flags & ts.TypeFlags.BooleanLiteral)&&new Set(parts.map(t=>t.intrinsicName)).size===2)return {type:'boolean'};
    if(parts.every(t=>t.isStringLiteral()||t.isNumberLiteral()||(t.flags & ts.TypeFlags.BooleanLiteral)))return {enum:[...new Set(parts.map(t=>t.isLiteral()?t.value:t.intrinsicName==='true'))]};
    if(parts.length===1)return schema(parts[0],depth+1);
    const choices=[...new Map(parts.map(t=>{const result=schema(t,depth+1);return[JSON.stringify(result),result];})).values()];
    return choices.length===1?choices[0]:{anyOf:choices};
  }
  if(type.flags & ts.TypeFlags.StringLike)return type.isStringLiteral()?{enum:[type.value]}:{type:'string'};
  if(type.flags & ts.TypeFlags.NumberLike)return type.isNumberLiteral()?{enum:[type.value]}:{type:'number'};
  if(type.flags & ts.TypeFlags.BooleanLike)return {type:'boolean'};
  if(type.flags & ts.TypeFlags.Null)return {type:'null'};
  if(checker.isArrayType(type))return {type:'array',items:schema(checker.getTypeArguments(type)[0],depth+1)};
  if(type.flags & ts.TypeFlags.Object){
    const props={},required=[];
    for(const p of checker.getPropertiesOfType(type)){
      const decl=p.valueDeclaration??p.declarations?.[0];
      // Finite mapped types can have synthesized keys with no declaration node.
      const propertyType=decl?checker.getTypeOfSymbolAtLocation(p,decl):checker.getTypeOfSymbol(p);
      const description=ts.displayPartsToString(p.getDocumentationComment(checker));
      props[p.name]={...schema(propertyType,depth+1),...(description?{description}:{})};
      if(!(p.flags & ts.SymbolFlags.Optional))required.push(p.name);
    }
    const index=checker.getIndexTypeOfType(type,ts.IndexKind.String);
    return {type:'object',properties:props,required,additionalProperties:index?schema(index,depth+1):false};
  }
  return {type:'unknown'};
}
const source=program.getSourceFile('src/types/index.ts');const result={};
for(const name of ['LlmHubSettings','WorkspaceState']){
  const node=source.statements.find(n=>n.name?.text===name);result[name]=schema(checker.getTypeAtLocation(node));
}
const guard=await readFile('src/safeguard/runtime.js','utf8');
// Extract only the literal defaults; no execution of the runtime/vendor module.
const defaults=guard.match(/const DEFAULT_SETTINGS = (\{[\s\S]*?\n\});/)[1];
const tree=ts.createSourceFile('defaults.js',`const defaults=${defaults}`,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
const literal=tree.statements[0].declarationList.declarations[0].initializer;
result.SafeGuard={type:'object',properties:Object.fromEntries(literal.properties.filter(p=>p.name?.getText()!=='contextMemories').map(p=>[p.name.getText(),{type:p.initializer.kind===ts.SyntaxKind.TrueKeyword||p.initializer.kind===ts.SyntaxKind.FalseKeyword?'boolean':ts.isNumericLiteral(p.initializer)?'number':'string',default:ts.isNumericLiteral(p.initializer)?Number(p.initializer.text):ts.isStringLiteral(p.initializer)?p.initializer.text:p.initializer.kind===ts.SyntaxKind.TrueKeyword}])) ,additionalProperties:false};
result.SafeGuard.properties.contextMemories={type:'object',additionalProperties:{type:'unknown'},default:{}};
await mkdir('src/configuration',{recursive:true});
await writeFile('src/configuration/generatedSchema.ts',`// Generated by scripts/generate-configuration-schema.mjs; do not edit.\nimport type {ConfigSchema} from './types';\nexport const CONFIGURATION_SCHEMAS: Record<string,ConfigSchema> = ${JSON.stringify(result,null,2)};\n`);
console.log('Generated configuration schemas from source types and Safe Guard defaults.');
